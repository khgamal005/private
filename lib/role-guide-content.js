export function buildPageTour(pageGuide){
  const custom=pageGuide.tour||[];
  if(custom.length)return custom.map((item,index)=>({
    id:`page-${pageGuide.key}-${index}`,
    ...item
  }));
  return [
    {
      id:`page-${pageGuide.key}-content`,
      selector:'.mt-content',
      title:pageGuide.title,
      body:pageGuide.description
    },
    {
      id:`page-${pageGuide.key}-action`,
      selector:'.mt-content button, .mt-content a',
      title:'ابدأ من الإجراء الواضح',
      body:pageGuide.steps?.[0]||'راجع بيانات الشاشة ثم نفّذ الإجراء المطلوب.'
    }
  ];
}
