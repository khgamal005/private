function clone(value){
  return JSON.parse(JSON.stringify(value));
}

function resolvedRole(roleKey){
  const selected=ROLE_GUIDES[roleKey]||ROLE_GUIDES.member;
  if(!selected.extends)return clone(selected);
  return clone({
    ...ROLE_GUIDES[selected.extends],
    ...selected,
    extends:undefined
  });
}

function hasPermission(permission,permissions,platformAccess){
  if(!permission||platformAccess)return true;
  const allowed=new Set(permissions||[]);
  const required=Array.isArray(permission)?permission:[permission];
  return required.some(item=>allowed.has(item));
}

export function getRoleGuide(roleKey,permissions=[],platformAccess=false){
  const guide=resolvedRole(roleKey);
  guide.workflows=(guide.workflows||[]).filter(item=>
    hasPermission(item.permission,permissions,platformAccess)
  );
  return guide;
}

export function pageKeyFromPath(pathname,slug){
  const base=`/tenant/${encodeURIComponent(slug||'')}`;
  const raw=String(pathname||'').split('?')[0];
  if(raw===base||raw===`${base}/`)return 'overview';
  const tail=raw.startsWith(`${base}/`)?raw.slice(base.length+1):raw;
  if(tail.startsWith('reports/employees')||tail.startsWith('reports/sales')||tail.startsWith('reports/campaigns'))return 'reports';
  if(tail.startsWith('calendar'))return 'tasks';
  if(tail.startsWith('knowledge'))return 'news';
  return Object.keys(PAGE_GUIDES)
    .sort((a,b)=>b.length-a.length)
    .find(key=>tail===key||tail.startsWith(`${key}/`))
    ||'overview';
}

export function getPageGuide(pathname,slug){
  const key=pageKeyFromPath(pathname,slug);
  return {key,...clone(PAGE_GUIDES[key]||PAGE_GUIDES.overview)};
}

export function hrefForGuide(slug,href){
  const base=`/tenant/${encodeURIComponent(slug)}`;
  if(!href||href==='overview')return base;
  return `${base}/${href}`;
}

